    assert.equal(await page.getByLabel('Model',{exact:true}).inputValue(),'UpdatedModel');
    await page.getByRole('button',{name:'Save changes',exact:true}).click();
    await page.getByText('UpdatedModel',{exact:true}).waitFor();
    await page.locator('.tools-compact-row').first().click();
