import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const mocks = path.resolve('tests/fixtures/inventory-pass-mocks.js');
const server = await createServer({ cacheDir: `.temp/inventory-pass/vite-${process.pid}`, plugins: [{ name: 'isolated-inventory-fixture', enforce: 'pre', resolveId(id) {
  if (id === '@clerk/clerk-react' || id.endsWith('/services/supabaseClient.js') || id.endsWith('/hooks/usePermissions.js')) return mocks;
} }], server: { host: '127.0.0.1', port: 5188, strictPort: true } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const url = 'http://127.0.0.1:5188/northgate/tests/fixtures/inventory-pass.html';
  await mkdir('.temp/inventory-pass/screenshots', { recursive: true });
  for (const [label, width, height] of [['desktop',1440,1000], ['tablet',768,1024], ['phone',390,844]]) {
    await page.setViewportSize({width,height});
    await page.goto(url);
    await page.getByText('2 materials', {exact:true}).waitFor();
    assert.equal(await page.getByText('No direct balance writes').count(), 0);
    assert.equal(await page.getByRole('button',{name:'Scan',exact:true}).count(),width>899 ? 0 : 2);
    assert.equal(await page.getByText('Lighting panel',{exact:true}).count(),0);
    await page.getByLabel('Search materials').fill('acme 3/4');
    assert.equal(await page.locator('.inventory-material').count(),1);
    await page.locator('.inventory-material summary').click();
    await page.getByLabel('Quantity for EMT connector at A1').fill('21');
    await page.locator('.inventory-stock-location').filter({hasText:'A1'}).getByRole('button',{name:'Add to Cart'}).click();
    await page.getByText('Enter a quantity greater than zero and no more than the available stock.').waitFor();
    assert.equal(await page.evaluate(()=>window.inventoryFixture.calls.filter(c=>c.name==='open_inventory_cart').length),0);
    await page.getByLabel('Quantity for EMT connector at A1').fill('3');
    await page.locator('.inventory-stock-location').filter({hasText:'A1'}).getByRole('button',{name:'Add to Cart'}).click();
    await page.getByText('Added 3.',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>window.inventoryFixture.calls.filter(c=>c.name==='open_inventory_cart').length),1);
    await page.screenshot({path:`.temp/inventory-pass/screenshots/${label}-search.png`,fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`${label} search overflow`);
    await page.getByRole('button',{name:'My Cart (1)',exact:true}).click();
    await page.getByRole('heading',{name:'My Cart',exact:true}).waitFor();
    assert.equal(await page.getByRole('option',{name:'User Possession'}).count(),0);
    assert.equal(await page.getByRole('button',{name:'Review Checkout'}).isDisabled(),true);
    await page.getByLabel('Cart destination note').fill('General shop supplies, no job coding');
    await page.getByRole('button',{name:'Apply To All',exact:true}).click();
    await page.getByRole('button',{name:'Review Checkout'}).click();
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await page.evaluate(()=>window.inventoryFixture.calls.filter(c=>c.name==='finalize_inventory_cart').length),0);
    await page.getByRole('button',{name:'Review Checkout'}).click();
    await page.screenshot({path:`.temp/inventory-pass/screenshots/${label}-cart.png`,fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`${label} cart overflow`);
    await page.getByRole('button',{name:'Confirm Checkout',exact:true}).click();
    await page.getByText('Cart finalized',{exact:true}).waitFor();
    const call = await page.evaluate(()=>window.inventoryFixture.calls.find(c=>c.name==='finalize_inventory_cart'));
    assert.equal(call.args.p_line_destinations[0].destination_type,'unknown');
    assert.equal(call.args.p_line_destinations[0].destination_id,null);
    assert.equal(call.args.p_line_destinations[0].note,'General shop supplies, no job coding');
  }
  await page.goto(`${url}?readonly`);
  await page.getByText('2 materials',{exact:true}).waitFor();
  await page.getByText('EMT connector',{exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Add to Cart'}).count(),0);
  assert.equal(await page.getByRole('button',{name:/My Cart/}).count(),0);
  await page.getByRole('button',{name:'Full Catalogue',exact:true}).click();
  await page.getByText('Lighting panel',{exact:true}).waitFor();
  await page.goto(`${url}?scan`);
  await page.getByText('2 materials',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('Stock location').inputValue(),'b1');
  await page.getByText('EMT connector',{exact:true}).click();
  assert.equal(await page.getByLabel('Quantity for EMT connector at VAN1').count(),0);
  await page.getByRole('button',{name:'Clear search and location'}).click();
  assert.equal(await page.getByLabel('Stock location').inputValue(),'');
  await page.evaluate(()=>window.inventoryFixture.failNext=true);
  await page.locator('.inventory-stock-location').filter({hasText:'A1'}).getByRole('button',{name:'Add to Cart'}).click();
  await page.getByText('Fixture stock changed. Retry.').waitFor();
  await page.locator('.inventory-stock-location').filter({hasText:'A1'}).getByRole('button',{name:'Add to Cart'}).click();
  await page.getByText('Added 1.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'My Cart (1)',exact:true}).click();
  await page.getByLabel('Cart destination type').selectOption('vehicle');
  await page.getByLabel('Cart destination reference').selectOption('van1');
  await page.getByRole('button',{name:'Apply To All',exact:true}).click();
  assert.equal(await page.getByLabel('Vehicle destination').inputValue(),'van1');
  await page.getByLabel('Destination note for EMT connector').fill('Restock');
  assert.equal(await page.getByLabel('Vehicle destination').inputValue(),'van1');
  await page.getByRole('button',{name:'Remove EMT connector',exact:true}).click();
  await page.getByText('Your cart is empty',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Scan',exact:true}).first().click();
  await page.getByLabel('Location code or QR').fill('A1');
  await page.getByRole('button',{name:'Open Scan Result',exact:true}).click();
  await page.getByRole('button',{name:'Select Materials',exact:true}).click();
  await page.getByText('2 materials',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('Stock location').inputValue(),'b1');
  await page.goto(`${url}?large`);
  await page.getByText('1003 materials',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>window.inventoryFixture.calls.some(c=>c.table==='inventory_cart_candidates_view' && c.range[0]===1000)),true);
  await page.getByLabel('Search materials').fill('Extra material 1000');
  await page.getByText('Extra material 1000',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: actual Inventory workspace and hooks; stock/catalogue, search, zero stock, 1000+ pagination, source selection, auto-open/add, validation, optional coding, review/cancel/finalize, failure, readonly, scan scope, and desktop/tablet/phone overflow.');
} finally { await browser?.close(); await server.close(); }
